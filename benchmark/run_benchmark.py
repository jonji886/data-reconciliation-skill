def _baseline_key(source_columns: list[str], target_columns: list[str]) -> tuple[str, str] | None:
    clean = lambda value: re.sub(r"[^a-z0-9\u4e00-\u9fff]", "", value.lower())
    for source in source_columns:
        for target in target_columns:
            if clean(source) == clean(target):
                return source, target
    return None


def _semantic_baseline_key(source_columns: list[str], target_columns: list[str]) -> tuple[str, str] | None:
    best: tuple[float, str, str] | None = None
    for source in source_columns:
        for target in target_columns:
            left, right = semantic_tokens(source), semantic_tokens(target)
            score = len(left & right) / max(len(left | right), 1)
            candidate = (score, source, target)
            if best is None or candidate > best:
                best = candidate
    return (best[1], best[2]) if best and best[0] > 0 else None


def _expected_missing(case: dict[str, Any]) -> int:
    source_key, target_key = case["expected_key"]
    source_keys = {normalize_key(value) for value in case["source"][source_key] if normalize_key(value) is not None}
    target_keys = {normalize_key(value) for value in case["target"][target_key] if normalize_key(value) is not None}
    return len(source_keys - target_keys) + len(target_keys - source_keys)


def run_case(case: dict[str, Any]) -> dict[str, Any]:
    started = time.perf_counter()
    left = LoadedTable(pd.DataFrame(case["source"]), f"{case['name']}_source.csv", None)
    right = LoadedTable(pd.DataFrame(case["target"]), f"{case['name']}_target.csv", None)
    left_profile, right_profile = profile_dataframe(left), profile_dataframe(right)
    candidates = detect_key_candidates(left_profile, right_profile, left.dataframe, right.dataframe)
    predicted_key = (candidates[0].source_column, candidates[0].target_column) if candidates else None
    suggestions = suggest_column_mappings(left_profile, right_profile, left.dataframe, right.dataframe)
    expected_pairs = set(case["expected_mappings"])
    predicted_pairs = {(item.source_column, item.target_column) for item in suggestions if item.target_column}
    true_positives = len(predicted_pairs & expected_pairs)
    safe_suggestions = [
        item
        for item in suggestions
        if item.target_column and not any(reason.startswith("MAPPING_COLLISION:") for reason in item.reasons)
    ]
    # The simulator accepts only non-high-risk proposals. Enum and ambiguous
    # mappings remain outside the deterministic comparison until a user confirms.
    confirmed = {item.source_column for item in safe_suggestions if not item.requires_confirmation}
    silent_high_risk = sum(
        1 for item in safe_suggestions if item.requires_confirmation and item.source_column in confirmed
    )
    try:
        rules = rules_from_suggestions(safe_suggestions, confirmed_columns=confirmed, numeric_tolerance=0.01)
    except Exception:
        rules = []
    if predicted_key:
        result = reconcile(
            left.dataframe,
            right.dataframe,
            source_key=predicted_key[0],
            target_key=predicted_key[1],
            rules=rules,
        )
        expected_missing = _expected_missing(case)
        predicted_missing = result.summary.missing_in_target + result.summary.missing_in_source
        expected_mismatches = case["expected_mismatches"]
        predicted_mismatches = result.summary.value_mismatches
        mismatch_precision = (
            min(predicted_mismatches, expected_mismatches) / predicted_mismatches
            if predicted_mismatches
            else (1.0 if expected_mismatches == 0 else 0.0)
        )
        missing_recall = min(predicted_missing / expected_missing, 1.0) if expected_missing else (1.0 if predicted_missing == 0 else 0.0)
    else:
        expected_missing = _expected_missing(case)
        predicted_missing = 0
        predicted_mismatches = 0
        mismatch_precision = 0.0
        missing_recall = 0.0
    return {
        "case": case["name"],
        "baseline_a_key_correct": _baseline_key(list(left.dataframe.columns), list(right.dataframe.columns)) == case["expected_key"],
        "baseline_b_key_correct": _semantic_baseline_key(list(left.dataframe.columns), list(right.dataframe.columns)) == case["expected_key"],
        "skill_key_correct": predicted_key == case["expected_key"],
        "mapping_true_positives": true_positives,
        "mapping_suggested": len(predicted_pairs),
        "mapping_expected": len(expected_pairs),
        "human_confirmations_required": sum(item.requires_confirmation for item in suggestions),
        "missing_record_recall": round(missing_recall, 4),
        "mismatch_precision": round(mismatch_precision, 4),
        "false_positive_count": max(predicted_mismatches - case["expected_mismatches"], 0),
        "silent_high_risk_mapping": silent_high_risk,
        "runtime_ms": round((time.perf_counter() - started) * 1000, 2),
        "llm_calls": 0,
    }


def main() -> None:
    case_results = [run_case(case) for case in CASES]
    mapping_tp = sum(item["mapping_true_positives"] for item in case_results)
    mapping_suggested = sum(item["mapping_suggested"] for item in case_results)
    mapping_expected = sum(item["mapping_expected"] for item in case_results)
    payload = {
        "cases": len(case_results),
        "key_detection_accuracy": round(sum(item["skill_key_correct"] for item in case_results) / len(case_results), 4),
        "mapping_precision": round(mapping_tp / mapping_suggested, 4) if mapping_suggested else 0.0,
        "mapping_recall": round(mapping_tp / mapping_expected, 4) if mapping_expected else 0.0,
        "missing_record_recall": round(sum(item["missing_record_recall"] for item in case_results) / len(case_results), 4),
        "mismatch_precision": round(sum(item["mismatch_precision"] for item in case_results) / len(case_results), 4),
        "false_positive_count": sum(item["false_positive_count"] for item in case_results),
        "confirmation_safety": {
            "silent_high_risk_mapping": sum(item["silent_high_risk_mapping"] for item in case_results),
            "required_confirmations": sum(item["human_confirmations_required"] for item in case_results),
        },
        "runtime_ms": round(sum(item["runtime_ms"] for item in case_results), 2),
        "llm_calls": sum(item["llm_calls"] for item in case_results),
        "baselines": {
            "exact_name_key_accuracy": round(sum(item["baseline_a_key_correct"] for item in case_results) / len(case_results), 4),
            "semantic_heuristic_key_accuracy": round(sum(item["baseline_b_key_correct"] for item in case_results) / len(case_results), 4),
        },
        "case_results": case_results,
    }
    output = Path(__file__).with_name("results.json")
    output.write_text(json.dumps(payload, ensure_ascii=False, indent=2), encoding="utf-8")
    print(json.dumps(payload, ensure_ascii=False, indent=2))


if __name__ == "__main__":
    main()
